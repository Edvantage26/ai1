// danger: shell commands that destroy work, history or data with no undo.
// `ask` stops and lets the person confirm in one click; `deny` refuses outright and is reserved for
// bypassing safety checks or wiping things nobody means to wipe.
// Options (`modules.danger` in .ai1/config.json):
//   ignore_rules: rule ids to switch off in this repo, e.g. ["rm-recursive-force"].

import { askDecision, denyDecision, allowDecision } from '../core/hook-io.mjs';
import { isAbsolute, resolve } from 'node:path';
import { splitSimpleCommands, baseName, hasShortFlag, hasLongFlag } from '../core/shell-parse.mjs';
import { listIgnoredPaths } from '../core/git.mjs';

const MODULE_ID = 'danger';

// Directories that are always regenerated by a build or install: deleting them is routine.
const REGENERABLE_DIRECTORY_NAMES = new Set([
  'node_modules', 'dist', 'build', 'out', '.next', '.nuxt', '.turbo', '.cache', 'coverage',
  '__pycache__', '.pytest_cache', '.mypy_cache', '.ruff_cache', '.tox', 'target', 'tmp', '.tmp',
]);
const CATASTROPHIC_RM_TARGETS = new Set(['/', '/*', '~', '~/', '~/*', '$HOME', '$HOME/', '${HOME}', '/home', '/root']);

// git global options that take a separate value: `git -C path status`.
const GIT_OPTIONS_WITH_VALUE = new Set(['-C', '-c', '--git-dir', '--work-tree', '--namespace']);

export function parseGitCommand(commandWords) {
  if (baseName(commandWords[0]) !== 'git') return null;
  const globalOptions = [];
  let wordIndex = 1;
  while (wordIndex < commandWords.length && commandWords[wordIndex].startsWith('-')) {
    const globalOption = commandWords[wordIndex];
    globalOptions.push(globalOption);
    if (GIT_OPTIONS_WITH_VALUE.has(globalOption)) {
      globalOptions.push(commandWords[wordIndex + 1]);
      wordIndex += 2;
    } else wordIndex += 1;
  }
  return { subcommand: commandWords[wordIndex], subcommandArgs: commandWords.slice(wordIndex + 1), globalOptions };
}

function isSafeRemovalTarget(removalTarget) {
  if (removalTarget.startsWith('/tmp/') || removalTarget.startsWith('/var/tmp/')) return true;
  const lastPathSegment = removalTarget.replace(/\/+$/, '').split('/').pop();
  return REGENERABLE_DIRECTORY_NAMES.has(lastPathSegment);
}

function gitWorkingDirectory(gitCommand, workingDirectory) {
  const directoryOptionIndex = gitCommand.globalOptions.indexOf('-C');
  const directoryOption = directoryOptionIndex >= 0 ? gitCommand.globalOptions[directoryOptionIndex + 1] : null;
  return directoryOption ? resolve(workingDirectory, directoryOption) : workingDirectory;
}

// Each rule returns { action, why } when it matches a simple command, or null. `ruleContext` carries
// the hook's working directory for the few rules that look at the disk.
export const DANGER_RULES = [
  {
    id: 'git-skip-hooks',
    check(commandWords) {
      const gitCommand = parseGitCommand(commandWords);
      if (!gitCommand) return null;
      const disablesHooksPath = gitCommand.globalOptions.some((globalOption) => /^core\.hooksPath=/i.test(globalOption ?? ''));
      const usesNoVerify = hasLongFlag(gitCommand.subcommandArgs, '--no-verify')
        || (gitCommand.subcommand === 'commit' && hasShortFlag(gitCommand.subcommandArgs, 'n'));
      if (!disablesHooksPath && !usesNoVerify) return null;
      return {
        action: 'deny',
        why: 'skips the git hooks (--no-verify / core.hooksPath). Fix what the hook reports instead; if the person wants to skip it, they run the command themselves.',
      };
    },
  },
  {
    id: 'git-reset-hard',
    check(commandWords) {
      const gitCommand = parseGitCommand(commandWords);
      if (gitCommand?.subcommand !== 'reset' || !hasLongFlag(gitCommand.subcommandArgs, '--hard')) return null;
      return { action: 'ask', why: 'git reset --hard discards uncommitted changes for good. Safer: git stash, or reset --soft/--mixed.' };
    },
  },
  {
    id: 'git-force-push',
    check(commandWords) {
      const gitCommand = parseGitCommand(commandWords);
      if (gitCommand?.subcommand !== 'push') return null;
      const forcesPush = hasLongFlag(gitCommand.subcommandArgs, '--force')
        || hasLongFlag(gitCommand.subcommandArgs, '--force-with-lease')
        || hasShortFlag(gitCommand.subcommandArgs, 'f')
        || gitCommand.subcommandArgs.some((pushArgument) => pushArgument.startsWith('+'));
      if (!forcesPush) return null;
      return { action: 'ask', why: 'a force push rewrites shared history on the remote.' };
    },
  },
  {
    id: 'git-clean',
    check(commandWords) {
      const gitCommand = parseGitCommand(commandWords);
      if (gitCommand?.subcommand !== 'clean') return null;
      const isDryRun = hasShortFlag(gitCommand.subcommandArgs, 'n') || hasLongFlag(gitCommand.subcommandArgs, '--dry-run');
      const forcesClean = hasShortFlag(gitCommand.subcommandArgs, 'f') || hasLongFlag(gitCommand.subcommandArgs, '--force');
      if (isDryRun || !forcesClean) return null;
      return { action: 'ask', why: 'git clean -f deletes untracked files, which git cannot recover. Run git clean -n first to list them.' };
    },
  },
  {
    id: 'git-discard-changes',
    check(commandWords) {
      const gitCommand = parseGitCommand(commandWords);
      if (!gitCommand) return null;
      const { subcommand, subcommandArgs } = gitCommand;
      const discardsWorkingTree = (subcommand === 'checkout' && (subcommandArgs.includes('--') || subcommandArgs.includes('.')))
        || (subcommand === 'restore' && !hasLongFlag(subcommandArgs, '--staged') && !hasShortFlag(subcommandArgs, 'S'))
        || (subcommand === 'stash' && ['drop', 'clear'].includes(subcommandArgs[0]))
        || (subcommand === 'branch' && (subcommandArgs.includes('-D') || (hasLongFlag(subcommandArgs, '--delete') && hasLongFlag(subcommandArgs, '--force'))));
      if (!discardsWorkingTree) return null;
      return { action: 'ask', why: `git ${subcommand} here throws away work that is not committed or not merged.` };
    },
  },
  {
    id: 'git-worktree-remove',
    check(commandWords, commandText, ruleContext = {}) {
      const gitCommand = parseGitCommand(commandWords);
      if (gitCommand?.subcommand !== 'worktree' || gitCommand.subcommandArgs[0] !== 'remove') return null;
      const removeArgs = gitCommand.subcommandArgs.slice(1);
      if (hasLongFlag(removeArgs, '--force') || hasShortFlag(removeArgs, 'f')) {
        return { action: 'ask', why: 'git worktree remove --force deletes the uncommitted and untracked files of that worktree for good. Commit or move them first.' };
      }
      const worktreeArgument = removeArgs.find((removeArg) => !removeArg.startsWith('-'));
      if (!worktreeArgument || !ruleContext.workingDirectory) return null;
      const baseDirectory = gitWorkingDirectory(gitCommand, ruleContext.workingDirectory);
      const worktreePath = isAbsolute(worktreeArgument) ? worktreeArgument : resolve(baseDirectory, worktreeArgument);
      const ignoredPaths = listIgnoredPaths(worktreePath);
      if (!ignoredPaths?.length) return null;
      const shownPaths = ignoredPaths.slice(0, 5).join(', ') + (ignoredPaths.length > 5 ? `, ... (${ignoredPaths.length} in total)` : '');
      return { action: 'ask', why: `git worktree remove also deletes the worktree's ignored files without asking: ${shownPaths}. Move what must be kept first.` };
    },
  },
  {
    id: 'ai1-worktree-drop',
    check(commandWords) {
      if (baseName(commandWords[0]) !== 'ai1' || commandWords[1] !== 'worktree' || commandWords[2] !== 'drop') return null;
      return { action: 'ask', why: 'ai1 worktree drop abandons the worktree and deletes its branch (its commits are kept in a bundle).' };
    },
  },
  {
    id: 'ai1-worktree-finish',
    check(commandWords) {
      if (baseName(commandWords[0]) !== 'ai1' || commandWords[1] !== 'worktree' || commandWords[2] !== 'finish') return null;
      return { action: 'ask', why: 'ai1 worktree finish integrates the branch into its base and removes the worktree: the person decides when.' };
    },
  },
  {
    id: 'ai1-proposals-new',
    check(commandWords) {
      if (baseName(commandWords[0]) !== 'ai1' || commandWords[1] !== 'proposals' || commandWords[2] !== 'new') return null;
      return { action: 'ask', why: 'ai1 proposals new creates a proposal: only the person decides that something becomes one.' };
    },
  },
  {
    id: 'rm-recursive-force',
    check(commandWords) {
      if (baseName(commandWords[0]) !== 'rm') return null;
      const removalOptions = commandWords.slice(1);
      const isRecursive = hasShortFlag(removalOptions, 'r') || hasShortFlag(removalOptions, 'R') || hasLongFlag(removalOptions, '--recursive');
      if (!isRecursive) return null;
      const removalTargets = removalOptions.filter((removalOption) => !removalOption.startsWith('-'));
      if (removalTargets.some((removalTarget) => CATASTROPHIC_RM_TARGETS.has(removalTarget))) {
        return { action: 'deny', why: 'rm -r on the root or the home directory. Name the exact paths to delete.' };
      }
      if (removalTargets.length && removalTargets.every(isSafeRemovalTarget)) return null;
      return { action: 'ask', why: `rm -r deletes ${removalTargets.join(' ') || 'files'} with no undo. Check the paths first.` };
    },
  },
  {
    id: 'find-delete',
    check(commandWords) {
      if (baseName(commandWords[0]) !== 'find' || !commandWords.includes('-delete')) return null;
      // Search roots are the words before the first expression (`-name`, `(`, `!`).
      const firstExpressionIndex = commandWords.findIndex((findWord, wordIndex) => wordIndex > 0 && /^[-(!]/.test(findWord));
      const searchRoots = commandWords.slice(1, firstExpressionIndex);
      if (searchRoots.length && searchRoots.every(isSafeRemovalTarget)) return null;
      return { action: 'ask', why: `find -delete deletes every match under ${searchRoots.join(' ') || '.'} with no undo. Run it without -delete first to list them.` };
    },
  },
  {
    id: 'file-truncate',
    check(commandWords) {
      if (baseName(commandWords[0]) !== 'truncate') return null;
      const truncateArgs = commandWords.slice(1);
      const sizeIndex = truncateArgs.findIndex((truncateArg) => truncateArg === '-s' || truncateArg === '--size');
      const newSize = sizeIndex >= 0
        ? truncateArgs[sizeIndex + 1]
        : truncateArgs.find((truncateArg) => /^(-s|--size=)/.test(truncateArg))?.replace(/^(-s|--size=)/, '');
      // `+N` only grows the file; any other size can cut it.
      if (newSize?.startsWith('+')) return null;
      return { action: 'ask', why: 'truncate cuts the file and the data past the new size is lost. Copy the file first.' };
    },
  },
  {
    id: 'sql-destructive',
    check(commandWords, commandText) {
      const dropsOrTruncates = /\b(drop\s+(table|database|schema|index|view)|truncate\s+(table\s+)?[a-z_"])/i.test(commandText);
      const deletesWithoutWhere = /\bdelete\s+from\s+[^\s;]+\s*(;|$|'|")/i.test(commandText);
      if (!dropsOrTruncates && !deletesWithoutWhere) return null;
      return { action: 'ask', why: 'the SQL drops or empties data (DROP / TRUNCATE / DELETE without WHERE). Back up or add a WHERE first.' };
    },
  },
  {
    id: 'docker-destructive',
    check(commandWords) {
      if (baseName(commandWords[0]) !== 'docker') return null;
      const dockerArgs = commandWords.slice(1);
      const removesData = (dockerArgs[0] === 'system' && dockerArgs[1] === 'prune')
        || (dockerArgs[0] === 'volume' && ['rm', 'prune'].includes(dockerArgs[1]))
        || (dockerArgs.includes('compose') && dockerArgs.includes('down') && (hasShortFlag(dockerArgs, 'v') || hasLongFlag(dockerArgs, '--volumes')));
      if (!removesData) return null;
      return { action: 'ask', why: 'the docker command deletes volumes or prunes data.' };
    },
  },
  {
    id: 'disk-destroy',
    check(commandWords) {
      const executableName = baseName(commandWords[0]);
      const writesRawDevice = executableName === 'dd' && commandWords.some((ddArgument) => /^of=\/dev\//.test(ddArgument));
      if (!executableName.startsWith('mkfs') && !writesRawDevice) return null;
      return { action: 'deny', why: 'it formats or overwrites a disk device.' };
    },
  },
];

export function findDangerousCommands(commandLine, ignoredRuleIds = [], ruleContext = {}) {
  const dangerFindings = [];
  for (const simpleCommand of splitSimpleCommands(commandLine)) {
    for (const dangerRule of DANGER_RULES) {
      if (ignoredRuleIds.includes(dangerRule.id)) continue;
      const ruleMatch = dangerRule.check(simpleCommand.words, simpleCommand.text, ruleContext);
      if (ruleMatch) dangerFindings.push({ ruleId: dangerRule.id, command: simpleCommand.text, ...ruleMatch });
    }
  }
  return dangerFindings;
}

export default {
  id: MODULE_ID,
  event: 'PreToolUse',
  toolNames: ['Bash'],
  feature: 'danger',
  description: 'Confirms or refuses shell commands that destroy work, history or data with no undo.',
  run({ hookInput, projectRoot, moduleOptions }) {
    const commandLine = hookInput.tool_input?.command;
    if (typeof commandLine !== 'string' || !commandLine.trim()) return allowDecision();
    const dangerFindings = findDangerousCommands(commandLine, moduleOptions.ignore_rules ?? [], { workingDirectory: hookInput.cwd || projectRoot });
    if (dangerFindings.length === 0) return allowDecision();
    const findingLines = dangerFindings.map((dangerFinding) => `[${dangerFinding.ruleId}] \`${dangerFinding.command}\`: ${dangerFinding.why}`);
    if (dangerFindings.some((dangerFinding) => dangerFinding.action === 'deny')) {
      return denyDecision(MODULE_ID, `${findingLines.join(' ')} Do not reach the same result another way; explain the risk and let the person decide.`);
    }
    return askDecision(MODULE_ID, findingLines.join(' '));
  },
};
