// Shared state of the `proposals` feature: proposals for changes that are not decided yet.
// One proposal = one versioned file `.ai1/proposals/NNNN-<slug>.md` with frontmatter
//   proposal: <number>, title, size: idea | full, status, created, updated, [decided], [superseded_by]
// and an index `.ai1/proposals/README.md` whose table is generated between two markers. A proposal is
// not the system: what is in force lives in the knowledge bundle, and an accepted proposal must be
// cited there (a concept with the proposal in `sources`) before the work counts as carried over.
// The CLI (`ai1 proposals ...`) and the proposals hooks both use these functions, so numbering, statuses and
// the index follow one set of rules.

import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { splitFrontmatter, readFrontmatterField, writeFrontmatterField } from '../core/frontmatter.mjs';
import { isFeatureEnabled } from '../core/features.mjs';
import { resolveBundleDirectory, readBundleIndex } from '../okf/okf-bundle.mjs';
import { KNOWLEDGE_BUNDLE_PATH, PROPOSALS_DIRECTORY } from '../core/config.mjs';
import { listMarkdownFiles } from '../core/markdown-files.mjs';

export { PROPOSALS_DIRECTORY };
export const PROPOSALS_INDEX_FILE = 'README.md';
export const PROPOSAL_STATUSES = ['draft', 'review', 'accepted', 'rejected', 'superseded', 'implemented'];
export const PROPOSAL_SIZES = ['idea', 'full'];
// Still waiting for a decision or for being built.
export const OPEN_PROPOSAL_STATUSES = new Set(['draft', 'review', 'accepted']);
// A decision was taken: the proposal records when.
const DECIDED_PROPOSAL_STATUSES = new Set(['accepted', 'rejected', 'implemented']);
// The decision is in force, so the knowledge bundle must say so.
const CARRIED_PROPOSAL_STATUSES = new Set(['accepted', 'implemented']);
const PROPOSAL_FILE_PATTERN = /^(\d{4})-([a-z0-9]+(?:-[a-z0-9]+)*)\.md$/;
const SLUG_PATTERN = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;
const DATE_PATTERN = /^\d{4}-\d{2}-\d{2}$/;
const INDEX_START_MARKER = '<!-- proposals-index:start (generated by `ai1 proposals index`; do not edit by hand) -->';
const INDEX_END_MARKER = '<!-- proposals-index:end -->';
const TEMPLATE_DIRECTORY = fileURLToPath(new URL('../../skills/proposals-write/templates/', import.meta.url));

export function padProposalNumber(proposalNumber) {
  return String(proposalNumber).padStart(4, '0');
}

export function todayDate(now = new Date()) {
  return now.toISOString().slice(0, 10);
}

export function proposalFilePrefix(proposalNumber) {
  return `${PROPOSALS_DIRECTORY}/${padProposalNumber(proposalNumber)}-`;
}

// Every proposal file in .ai1/proposals, by number: { number, fileNumber, slug, fileName, relativePath, absolutePath,
// title, size, status, created, updated, decided, supersededBy, hasFrontmatter, bodyText }.
export function listProposals(projectRoot) {
  const proposalDirectory = join(projectRoot, PROPOSALS_DIRECTORY);
  if (!existsSync(proposalDirectory)) return [];
  const proposalDocuments = [];
  for (const fileName of readdirSync(proposalDirectory)) {
    const fileMatch = PROPOSAL_FILE_PATTERN.exec(fileName);
    if (!fileMatch) continue;
    const absolutePath = join(proposalDirectory, fileName);
    const { frontmatterText, bodyText } = splitFrontmatter(readFileSync(absolutePath, 'utf8'));
    const readField = (fieldName) => readFrontmatterField(frontmatterText, fieldName);
    proposalDocuments.push({
      number: Number(readField('proposal')) || null,
      fileNumber: Number(fileMatch[1]),
      slug: fileMatch[2],
      fileName,
      relativePath: `${PROPOSALS_DIRECTORY}/${fileName}`,
      absolutePath,
      title: readField('title'),
      size: readField('size'),
      status: readField('status'),
      created: readField('created'),
      updated: readField('updated'),
      decided: readField('decided'),
      supersededBy: Number(readField('superseded_by')) || null,
      hasFrontmatter: frontmatterText !== null,
      bodyText,
    });
  }
  return proposalDocuments.sort((firstProposal, secondProposal) => firstProposal.fileNumber - secondProposal.fileNumber);
}

export function findProposal(proposalDocuments, proposalNumber) {
  return proposalDocuments.find((proposalDocument) => proposalDocument.fileNumber === Number(proposalNumber));
}

export function describeProposalStatus(proposalDocument) {
  return proposalDocument.status === 'superseded' && proposalDocument.supersededBy
    ? `superseded by ${padProposalNumber(proposalDocument.supersededBy)}`
    : proposalDocument.status;
}

function buildIndexTable(proposalDocuments) {
  return [
    INDEX_START_MARKER,
    '| No. | Title | Size | Status | Created | Updated |',
    '|---|---|---|---|---|---|',
    ...proposalDocuments.map((proposalDocument) => `| [${padProposalNumber(proposalDocument.fileNumber)}](${proposalDocument.fileName}) | ${proposalDocument.title || proposalDocument.slug} | ${proposalDocument.size} | ${describeProposalStatus(proposalDocument)} | ${proposalDocument.created} | ${proposalDocument.updated} |`),
    INDEX_END_MARKER,
  ].join('\n');
}

function buildNewIndexText(indexTable, knowledgePath) {
  const knowledgeText = knowledgePath ? `the knowledge bundle (\`${knowledgePath}/\`)` : 'the project documentation';
  return [
    '# Proposals',
    '',
    `Proposals for large changes and future features. A proposal is not the system: what is in force lives in ${knowledgeText}.`,
    'Create and change proposals with `ai1 proposals new` and `ai1 proposals set`; this table is regenerated by them.',
    '',
    indexTable,
    '',
  ].join('\n');
}

// The index text that matches the proposal files: the existing README with its table replaced, or a new one.
export function renderProposalIndex(projectRoot, knowledgePath, proposalDocuments = listProposals(projectRoot)) {
  const indexPath = join(projectRoot, PROPOSALS_DIRECTORY, PROPOSALS_INDEX_FILE);
  const indexTable = buildIndexTable(proposalDocuments);
  if (!existsSync(indexPath)) return buildNewIndexText(indexTable, knowledgePath);
  const currentIndexText = readFileSync(indexPath, 'utf8');
  const startIndex = currentIndexText.indexOf(INDEX_START_MARKER);
  const endIndex = currentIndexText.indexOf(INDEX_END_MARKER);
  if (startIndex < 0 || endIndex < startIndex) return `${currentIndexText.trimEnd()}\n\n${indexTable}\n`;
  return currentIndexText.slice(0, startIndex) + indexTable + currentIndexText.slice(endIndex + INDEX_END_MARKER.length);
}

export function writeProposalIndex(projectRoot, knowledgePath) {
  const indexPath = join(projectRoot, PROPOSALS_DIRECTORY, PROPOSALS_INDEX_FILE);
  mkdirSync(join(projectRoot, PROPOSALS_DIRECTORY), { recursive: true });
  writeFileSync(indexPath, renderProposalIndex(projectRoot, knowledgePath));
  return `${PROPOSALS_DIRECTORY}/${PROPOSALS_INDEX_FILE}`;
}

// Where the index and the brief say decisions live: the bundle path when the okf feature is on.
export function resolveKnowledgePath(config) {
  return isFeatureEnabled('okf', config) ? KNOWLEDGE_BUNDLE_PATH : null;
}

// Bundle to check citations against: only when the okf feature is on and the bundle exists.
export function resolveCitingBundle(projectRoot, config) {
  if (!isFeatureEnabled('okf', config)) return null;
  const bundleDirectory = resolveBundleDirectory(projectRoot);
  return readBundleIndex(bundleDirectory) === null ? null : bundleDirectory;
}

// Problems that make the proposal folder inconsistent. `bundleDirectory` (when the okf feature is on)
// adds the rule that an accepted or implemented proposal is cited by at least one bundle concept.
export function checkProposals(projectRoot, { knowledgePath = null, bundleDirectory = null } = {}) {
  const proposalDocuments = listProposals(projectRoot);
  const proposalProblems = [];
  const seenNumbers = new Map();
  const bundleTexts = bundleDirectory ? listMarkdownFiles(bundleDirectory).map((bundleFile) => readFileSync(bundleFile, 'utf8')) : null;
  for (const proposalDocument of proposalDocuments) {
    const proposalLabel = proposalDocument.relativePath;
    if (seenNumbers.has(proposalDocument.fileNumber)) proposalProblems.push(`${proposalLabel}: number ${padProposalNumber(proposalDocument.fileNumber)} is also used by ${seenNumbers.get(proposalDocument.fileNumber)}`);
    seenNumbers.set(proposalDocument.fileNumber, proposalLabel);
    if (!proposalDocument.hasFrontmatter) {
      proposalProblems.push(`${proposalLabel}: no frontmatter (proposal, title, size, status, created, updated)`);
      continue;
    }
    if (proposalDocument.number !== proposalDocument.fileNumber) proposalProblems.push(`${proposalLabel}: \`proposal: ${proposalDocument.number ?? ''}\` does not match the file number ${proposalDocument.fileNumber}`);
    if (!proposalDocument.title) proposalProblems.push(`${proposalLabel}: missing \`title\``);
    if (!PROPOSAL_SIZES.includes(proposalDocument.size)) proposalProblems.push(`${proposalLabel}: \`size\` must be one of ${PROPOSAL_SIZES.join(', ')}`);
    if (!PROPOSAL_STATUSES.includes(proposalDocument.status)) proposalProblems.push(`${proposalLabel}: \`status\` must be one of ${PROPOSAL_STATUSES.join(', ')}`);
    for (const dateField of ['created', 'updated']) {
      if (!DATE_PATTERN.test(proposalDocument[dateField])) proposalProblems.push(`${proposalLabel}: \`${dateField}\` must be a date (YYYY-MM-DD)`);
    }
    if (DECIDED_PROPOSAL_STATUSES.has(proposalDocument.status) && !DATE_PATTERN.test(proposalDocument.decided)) {
      proposalProblems.push(`${proposalLabel}: status ${proposalDocument.status} needs \`decided: YYYY-MM-DD\` and its Outcome section filled in`);
    }
    if (proposalDocument.status === 'superseded' && !findProposal(proposalDocuments, proposalDocument.supersededBy)) {
      proposalProblems.push(`${proposalLabel}: status superseded needs \`superseded_by: <number>\` naming an existing proposal`);
    }
    if (bundleTexts && CARRIED_PROPOSAL_STATUSES.has(proposalDocument.status)
      && !bundleTexts.some((bundleText) => bundleText.includes(proposalFilePrefix(proposalDocument.fileNumber)))) {
      proposalProblems.push(`${proposalLabel}: ${proposalDocument.status} but no concept in ${knowledgePath}/ cites it; record its decisions as concepts (type Decision, \`sources: - resource: ${proposalLabel}\`) with /ai1:okf-maintain-knowledge`);
    }
  }
  const indexPath = join(projectRoot, PROPOSALS_DIRECTORY, PROPOSALS_INDEX_FILE);
  if (proposalDocuments.length && (!existsSync(indexPath) || readFileSync(indexPath, 'utf8') !== renderProposalIndex(projectRoot, knowledgePath, proposalDocuments))) {
    proposalProblems.push(`${PROPOSALS_DIRECTORY}/${PROPOSALS_INDEX_FILE} is out of date: run \`ai1 proposals index\``);
  }
  return proposalProblems;
}

// A title with YAML-significant characters (`: `, `#`, a leading quote or bracket) goes in double quotes.
function frontmatterTitle(titleText) {
  const singleLineTitle = titleText.replace(/\n/g, ' ').trim();
  return /: |\s#|^["'\[{&*!|>%@`]/.test(singleLineTitle) ? JSON.stringify(singleLineTitle) : singleLineTitle;
}

function titleFromSlug(slug) {
  const spacedSlug = slug.replace(/-/g, ' ');
  return spacedSlug.charAt(0).toUpperCase() + spacedSlug.slice(1);
}

// Creates .ai1/proposals/NNNN-<slug>.md from the idea or full template with the next free number, and
// regenerates the index. Returns { proposalNumber, relativePath, indexPath }.
export function createProposal(projectRoot, { slug, title, size = 'full', knowledgePath = null, today = todayDate() }) {
  if (!SLUG_PATTERN.test(slug || '')) throw new Error(`the slug must be lowercase words joined by dashes, e.g. prod-guard (got "${slug ?? ''}")`);
  if (!PROPOSAL_SIZES.includes(size)) throw new Error(`size must be one of ${PROPOSAL_SIZES.join(', ')}`);
  const proposalDocuments = listProposals(projectRoot);
  const sameSlugProposal = proposalDocuments.find((proposalDocument) => proposalDocument.slug === slug);
  if (sameSlugProposal) throw new Error(`${sameSlugProposal.relativePath} already uses the slug "${slug}"`);
  const proposalNumber = Math.max(0, ...proposalDocuments.map((proposalDocument) => proposalDocument.fileNumber)) + 1;
  const proposalText = readFileSync(join(TEMPLATE_DIRECTORY, `${size}.md`), 'utf8')
    .replaceAll('{{number}}', String(proposalNumber))
    .replaceAll('{{padded_number}}', padProposalNumber(proposalNumber))
    // Replacer functions, so `$&` or `$$` in a title are written as they are.
    .replace('title: {{title}}', () => `title: ${frontmatterTitle(title || titleFromSlug(slug))}`)
    .replaceAll('{{title}}', () => (title || titleFromSlug(slug)).replace(/\n/g, ' ').trim())
    .replaceAll('{{date}}', today);
  mkdirSync(join(projectRoot, PROPOSALS_DIRECTORY), { recursive: true });
  const relativePath = `${PROPOSALS_DIRECTORY}/${padProposalNumber(proposalNumber)}-${slug}.md`;
  writeFileSync(join(projectRoot, relativePath), proposalText);
  return { proposalNumber, relativePath, indexPath: writeProposalIndex(projectRoot, knowledgePath) };
}

// Adds a line at the end of the History section (created when missing), keeping the spacing around it.
function appendHistoryLine(proposalText, historyLine) {
  const historyMatch = /^## History[^\n]*\n/m.exec(proposalText);
  if (!historyMatch) return `${proposalText.trimEnd()}\n\n## History\n\n${historyLine}\n`;
  const sectionStart = historyMatch.index + historyMatch[0].length;
  const nextHeadingOffset = proposalText.slice(sectionStart).search(/^## /m);
  const sectionEnd = nextHeadingOffset < 0 ? proposalText.length : sectionStart + nextHeadingOffset;
  const sectionBody = proposalText.slice(sectionStart, sectionEnd);
  const trimmedBody = sectionBody.trimEnd();
  const trailingSpace = sectionBody.slice(trimmedBody.length) || '\n';
  return `${proposalText.slice(0, sectionStart)}${trimmedBody}\n${historyLine}${trailingSpace}${proposalText.slice(sectionEnd)}`;
}

// Moves a proposal to a new status: frontmatter (`status`, `updated`, `decided` when a decision is taken,
// `superseded_by`), a line in its History section, and the index. Returns { relativePath, indexPath }.
export function setProposalStatus(projectRoot, proposalNumber, newStatus, { supersededBy = null, knowledgePath = null, today = todayDate() } = {}) {
  if (!PROPOSAL_STATUSES.includes(newStatus)) throw new Error(`status must be one of ${PROPOSAL_STATUSES.join(', ')}`);
  const proposalDocuments = listProposals(projectRoot);
  const proposalDocument = findProposal(proposalDocuments, proposalNumber);
  if (!proposalDocument) throw new Error(`no proposal number ${proposalNumber} in ${PROPOSALS_DIRECTORY}/`);
  if (newStatus === 'superseded' && !findProposal(proposalDocuments, supersededBy)) throw new Error('superseded needs --by <number> naming an existing proposal');
  let proposalText = readFileSync(proposalDocument.absolutePath, 'utf8');
  proposalText = writeFrontmatterField(proposalText, 'status', newStatus);
  proposalText = writeFrontmatterField(proposalText, 'updated', today);
  if (DECIDED_PROPOSAL_STATUSES.has(newStatus) && (newStatus !== 'implemented' || !proposalDocument.decided)) {
    proposalText = writeFrontmatterField(proposalText, 'decided', today);
  }
  if (newStatus === 'superseded') proposalText = writeFrontmatterField(proposalText, 'superseded_by', Number(supersededBy));
  const statusText = newStatus === 'superseded' ? `superseded by proposal ${padProposalNumber(supersededBy)}` : newStatus;
  proposalText = appendHistoryLine(proposalText, `- ${today}: status ${statusText}`);
  writeFileSync(proposalDocument.absolutePath, proposalText);
  return { relativePath: proposalDocument.relativePath, indexPath: writeProposalIndex(projectRoot, knowledgePath) };
}
