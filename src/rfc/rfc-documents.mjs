// Shared state of the `rfc` feature: proposals for changes that are not decided yet.
// One RFC = one versioned file `.ai1/rfc/NNNN-<slug>.md` with frontmatter
//   rfc: <number>, title, size: idea | full, status, created, updated, [decided], [superseded_by]
// and an index `.ai1/rfc/README.md` whose table is generated between two markers. A proposal is
// not the system: what is in force lives in the knowledge bundle, and an accepted RFC must be
// cited there (a concept with the RFC in `sources`) before the work counts as carried over.
// The CLI (`ai1 rfc ...`) and the rfc hooks both use these functions, so numbering, statuses and
// the index follow one set of rules.

import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { splitFrontmatter, readFrontmatterField, writeFrontmatterField } from '../core/frontmatter.mjs';
import { isFeatureEnabled } from '../core/features.mjs';
import { resolveBundleDirectory, readBundleIndex } from '../okf/okf-bundle.mjs';

export const RFC_DIRECTORY = '.ai1/rfc';
export const RFC_INDEX_FILE = 'README.md';
export const RFC_STATUSES = ['draft', 'review', 'accepted', 'rejected', 'superseded', 'implemented'];
export const RFC_SIZES = ['idea', 'full'];
// Still waiting for a decision or for being built.
export const OPEN_RFC_STATUSES = new Set(['draft', 'review', 'accepted']);
// A decision was taken: the RFC records when.
const DECIDED_RFC_STATUSES = new Set(['accepted', 'rejected', 'implemented']);
// The decision is in force, so the knowledge bundle must say so.
const CARRIED_RFC_STATUSES = new Set(['accepted', 'implemented']);
const RFC_FILE_PATTERN = /^(\d{4})-([a-z0-9]+(?:-[a-z0-9]+)*)\.md$/;
const SLUG_PATTERN = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;
const DATE_PATTERN = /^\d{4}-\d{2}-\d{2}$/;
const INDEX_START_MARKER = '<!-- rfc-index:start (generated by `ai1 rfc index`; do not edit by hand) -->';
const INDEX_END_MARKER = '<!-- rfc-index:end -->';
const TEMPLATE_DIRECTORY = fileURLToPath(new URL('../../skills/rfc-write-proposal/templates/', import.meta.url));

export function padRfcNumber(rfcNumber) {
  return String(rfcNumber).padStart(4, '0');
}

export function todayDate(now = new Date()) {
  return now.toISOString().slice(0, 10);
}

export function rfcFilePrefix(rfcNumber) {
  return `${RFC_DIRECTORY}/${padRfcNumber(rfcNumber)}-`;
}

// Every RFC file in .ai1/rfc, by number: { number, fileNumber, slug, fileName, relativePath, absolutePath,
// title, size, status, created, updated, decided, supersededBy, hasFrontmatter, bodyText }.
export function listRfcs(projectRoot) {
  const rfcDirectory = join(projectRoot, RFC_DIRECTORY);
  if (!existsSync(rfcDirectory)) return [];
  const rfcDocuments = [];
  for (const fileName of readdirSync(rfcDirectory)) {
    const fileMatch = RFC_FILE_PATTERN.exec(fileName);
    if (!fileMatch) continue;
    const absolutePath = join(rfcDirectory, fileName);
    const { frontmatterText, bodyText } = splitFrontmatter(readFileSync(absolutePath, 'utf8'));
    const readField = (fieldName) => readFrontmatterField(frontmatterText, fieldName);
    rfcDocuments.push({
      number: Number(readField('rfc')) || null,
      fileNumber: Number(fileMatch[1]),
      slug: fileMatch[2],
      fileName,
      relativePath: `${RFC_DIRECTORY}/${fileName}`,
      absolutePath,
      title: readField('title'),
      size: readField('size'),
      status: readField('status'),
      created: readField('created'),
      updated: readField('updated'),
      decided: readField('decided'),
      supersededBy: Number(readField('superseded_by')) || null,
      hasFrontmatter: frontmatterText !== null,
      bodyText,
    });
  }
  return rfcDocuments.sort((firstRfc, secondRfc) => firstRfc.fileNumber - secondRfc.fileNumber);
}

export function findRfc(rfcDocuments, rfcNumber) {
  return rfcDocuments.find((rfcDocument) => rfcDocument.fileNumber === Number(rfcNumber));
}

export function describeRfcStatus(rfcDocument) {
  return rfcDocument.status === 'superseded' && rfcDocument.supersededBy
    ? `superseded by ${padRfcNumber(rfcDocument.supersededBy)}`
    : rfcDocument.status;
}

function buildIndexTable(rfcDocuments) {
  return [
    INDEX_START_MARKER,
    '| No. | Title | Size | Status | Created | Updated |',
    '|---|---|---|---|---|---|',
    ...rfcDocuments.map((rfcDocument) => `| [${padRfcNumber(rfcDocument.fileNumber)}](${rfcDocument.fileName}) | ${rfcDocument.title || rfcDocument.slug} | ${rfcDocument.size} | ${describeRfcStatus(rfcDocument)} | ${rfcDocument.created} | ${rfcDocument.updated} |`),
    INDEX_END_MARKER,
  ].join('\n');
}

function buildNewIndexText(indexTable, knowledgePath) {
  const knowledgeText = knowledgePath ? `the knowledge bundle (\`${knowledgePath}/\`)` : 'the project documentation';
  return [
    '# RFCs',
    '',
    `Proposals for large changes and future features. A proposal is not the system: what is in force lives in ${knowledgeText}.`,
    'Create and change RFCs with `ai1 rfc new` and `ai1 rfc set`; this table is regenerated by them.',
    '',
    indexTable,
    '',
  ].join('\n');
}

// The index text that matches the RFC files: the existing README with its table replaced, or a new one.
export function renderRfcIndex(projectRoot, knowledgePath, rfcDocuments = listRfcs(projectRoot)) {
  const indexPath = join(projectRoot, RFC_DIRECTORY, RFC_INDEX_FILE);
  const indexTable = buildIndexTable(rfcDocuments);
  if (!existsSync(indexPath)) return buildNewIndexText(indexTable, knowledgePath);
  const currentIndexText = readFileSync(indexPath, 'utf8');
  const startIndex = currentIndexText.indexOf(INDEX_START_MARKER);
  const endIndex = currentIndexText.indexOf(INDEX_END_MARKER);
  if (startIndex < 0 || endIndex < startIndex) return `${currentIndexText.trimEnd()}\n\n${indexTable}\n`;
  return currentIndexText.slice(0, startIndex) + indexTable + currentIndexText.slice(endIndex + INDEX_END_MARKER.length);
}

export function writeRfcIndex(projectRoot, knowledgePath) {
  const indexPath = join(projectRoot, RFC_DIRECTORY, RFC_INDEX_FILE);
  mkdirSync(join(projectRoot, RFC_DIRECTORY), { recursive: true });
  writeFileSync(indexPath, renderRfcIndex(projectRoot, knowledgePath));
  return `${RFC_DIRECTORY}/${RFC_INDEX_FILE}`;
}

function listBundleFiles(directoryPath) {
  if (!existsSync(directoryPath)) return [];
  return readdirSync(directoryPath, { withFileTypes: true }).flatMap((directoryEntry) => {
    const entryPath = join(directoryPath, directoryEntry.name);
    if (directoryEntry.isDirectory()) return listBundleFiles(entryPath);
    return directoryEntry.name.endsWith('.md') ? [entryPath] : [];
  });
}

// Where the index and the brief say decisions live: the bundle path when the okf feature is on.
export function resolveKnowledgePath(config) {
  return isFeatureEnabled('okf', config) && config.knowledge ? config.knowledge : null;
}

// Bundle to check citations against: only when the okf feature is on and the bundle exists.
export function resolveCitingBundle(projectRoot, config) {
  if (!isFeatureEnabled('okf', config) || !config.knowledge) return null;
  const bundleDirectory = resolveBundleDirectory(projectRoot, config);
  return readBundleIndex(bundleDirectory) === null ? null : bundleDirectory;
}

// Problems that make the RFC folder inconsistent. `bundleDirectory` (when the okf feature is on)
// adds the rule that an accepted or implemented RFC is cited by at least one bundle concept.
export function checkRfcs(projectRoot, { knowledgePath = null, bundleDirectory = null } = {}) {
  const rfcDocuments = listRfcs(projectRoot);
  const rfcProblems = [];
  const seenNumbers = new Map();
  const bundleTexts = bundleDirectory ? listBundleFiles(bundleDirectory).map((bundleFile) => readFileSync(bundleFile, 'utf8')) : null;
  for (const rfcDocument of rfcDocuments) {
    const rfcLabel = rfcDocument.relativePath;
    if (seenNumbers.has(rfcDocument.fileNumber)) rfcProblems.push(`${rfcLabel}: number ${padRfcNumber(rfcDocument.fileNumber)} is also used by ${seenNumbers.get(rfcDocument.fileNumber)}`);
    seenNumbers.set(rfcDocument.fileNumber, rfcLabel);
    if (!rfcDocument.hasFrontmatter) {
      rfcProblems.push(`${rfcLabel}: no frontmatter (rfc, title, size, status, created, updated)`);
      continue;
    }
    if (rfcDocument.number !== rfcDocument.fileNumber) rfcProblems.push(`${rfcLabel}: \`rfc: ${rfcDocument.number ?? ''}\` does not match the file number ${rfcDocument.fileNumber}`);
    if (!rfcDocument.title) rfcProblems.push(`${rfcLabel}: missing \`title\``);
    if (!RFC_SIZES.includes(rfcDocument.size)) rfcProblems.push(`${rfcLabel}: \`size\` must be one of ${RFC_SIZES.join(', ')}`);
    if (!RFC_STATUSES.includes(rfcDocument.status)) rfcProblems.push(`${rfcLabel}: \`status\` must be one of ${RFC_STATUSES.join(', ')}`);
    for (const dateField of ['created', 'updated']) {
      if (!DATE_PATTERN.test(rfcDocument[dateField])) rfcProblems.push(`${rfcLabel}: \`${dateField}\` must be a date (YYYY-MM-DD)`);
    }
    if (DECIDED_RFC_STATUSES.has(rfcDocument.status) && !DATE_PATTERN.test(rfcDocument.decided)) {
      rfcProblems.push(`${rfcLabel}: status ${rfcDocument.status} needs \`decided: YYYY-MM-DD\` and its Outcome section filled in`);
    }
    if (rfcDocument.status === 'superseded' && !findRfc(rfcDocuments, rfcDocument.supersededBy)) {
      rfcProblems.push(`${rfcLabel}: status superseded needs \`superseded_by: <number>\` naming an existing RFC`);
    }
    if (bundleTexts && CARRIED_RFC_STATUSES.has(rfcDocument.status)
      && !bundleTexts.some((bundleText) => bundleText.includes(rfcFilePrefix(rfcDocument.fileNumber)))) {
      rfcProblems.push(`${rfcLabel}: ${rfcDocument.status} but no concept in ${knowledgePath}/ cites it; record its decisions as concepts (type Decision, \`sources: - resource: ${rfcLabel}\`) with /ai1:okf-maintain-knowledge`);
    }
  }
  const indexPath = join(projectRoot, RFC_DIRECTORY, RFC_INDEX_FILE);
  if (rfcDocuments.length && (!existsSync(indexPath) || readFileSync(indexPath, 'utf8') !== renderRfcIndex(projectRoot, knowledgePath, rfcDocuments))) {
    rfcProblems.push(`${RFC_DIRECTORY}/${RFC_INDEX_FILE} is out of date: run \`ai1 rfc index\``);
  }
  return rfcProblems;
}

// A title with YAML-significant characters (`: `, `#`, a leading quote or bracket) goes in double quotes.
function frontmatterTitle(titleText) {
  const singleLineTitle = titleText.replace(/\n/g, ' ').trim();
  return /: |\s#|^["'\[{&*!|>%@`]/.test(singleLineTitle) ? JSON.stringify(singleLineTitle) : singleLineTitle;
}

function titleFromSlug(slug) {
  const spacedSlug = slug.replace(/-/g, ' ');
  return spacedSlug.charAt(0).toUpperCase() + spacedSlug.slice(1);
}

// Creates .ai1/rfc/NNNN-<slug>.md from the idea or full template with the next free number, and
// regenerates the index. Returns { rfcNumber, relativePath, indexPath }.
export function createRfc(projectRoot, { slug, title, size = 'full', knowledgePath = null, today = todayDate() }) {
  if (!SLUG_PATTERN.test(slug || '')) throw new Error(`the slug must be lowercase words joined by dashes, e.g. prod-guard (got "${slug ?? ''}")`);
  if (!RFC_SIZES.includes(size)) throw new Error(`size must be one of ${RFC_SIZES.join(', ')}`);
  const rfcDocuments = listRfcs(projectRoot);
  const sameSlugRfc = rfcDocuments.find((rfcDocument) => rfcDocument.slug === slug);
  if (sameSlugRfc) throw new Error(`${sameSlugRfc.relativePath} already uses the slug "${slug}"`);
  const rfcNumber = Math.max(0, ...rfcDocuments.map((rfcDocument) => rfcDocument.fileNumber)) + 1;
  const rfcText = readFileSync(join(TEMPLATE_DIRECTORY, `${size}.md`), 'utf8')
    .replaceAll('{{number}}', String(rfcNumber))
    .replaceAll('{{padded_number}}', padRfcNumber(rfcNumber))
    .replace('title: {{title}}', `title: ${frontmatterTitle(title || titleFromSlug(slug))}`)
    .replaceAll('{{title}}', (title || titleFromSlug(slug)).replace(/\n/g, ' ').trim())
    .replaceAll('{{date}}', today);
  mkdirSync(join(projectRoot, RFC_DIRECTORY), { recursive: true });
  const relativePath = `${RFC_DIRECTORY}/${padRfcNumber(rfcNumber)}-${slug}.md`;
  writeFileSync(join(projectRoot, relativePath), rfcText);
  return { rfcNumber, relativePath, indexPath: writeRfcIndex(projectRoot, knowledgePath) };
}

// Adds a line at the end of the History section (created when missing), keeping the spacing around it.
function appendHistoryLine(rfcText, historyLine) {
  const historyMatch = /^## History[^\n]*\n/m.exec(rfcText);
  if (!historyMatch) return `${rfcText.trimEnd()}\n\n## History\n\n${historyLine}\n`;
  const sectionStart = historyMatch.index + historyMatch[0].length;
  const nextHeadingOffset = rfcText.slice(sectionStart).search(/^## /m);
  const sectionEnd = nextHeadingOffset < 0 ? rfcText.length : sectionStart + nextHeadingOffset;
  const sectionBody = rfcText.slice(sectionStart, sectionEnd);
  const trimmedBody = sectionBody.trimEnd();
  const trailingSpace = sectionBody.slice(trimmedBody.length) || '\n';
  return `${rfcText.slice(0, sectionStart)}${trimmedBody}\n${historyLine}${trailingSpace}${rfcText.slice(sectionEnd)}`;
}

// Moves an RFC to a new status: frontmatter (`status`, `updated`, `decided` when a decision is taken,
// `superseded_by`), a line in its History section, and the index. Returns { relativePath, indexPath }.
export function setRfcStatus(projectRoot, rfcNumber, newStatus, { supersededBy = null, knowledgePath = null, today = todayDate() } = {}) {
  if (!RFC_STATUSES.includes(newStatus)) throw new Error(`status must be one of ${RFC_STATUSES.join(', ')}`);
  const rfcDocuments = listRfcs(projectRoot);
  const rfcDocument = findRfc(rfcDocuments, rfcNumber);
  if (!rfcDocument) throw new Error(`no RFC number ${rfcNumber} in ${RFC_DIRECTORY}/`);
  if (newStatus === 'superseded' && !findRfc(rfcDocuments, supersededBy)) throw new Error('superseded needs --by <number> naming an existing RFC');
  let rfcText = readFileSync(rfcDocument.absolutePath, 'utf8');
  rfcText = writeFrontmatterField(rfcText, 'status', newStatus);
  rfcText = writeFrontmatterField(rfcText, 'updated', today);
  if (DECIDED_RFC_STATUSES.has(newStatus) && (newStatus !== 'implemented' || !rfcDocument.decided)) {
    rfcText = writeFrontmatterField(rfcText, 'decided', today);
  }
  if (newStatus === 'superseded') rfcText = writeFrontmatterField(rfcText, 'superseded_by', Number(supersededBy));
  const statusText = newStatus === 'superseded' ? `superseded by RFC ${padRfcNumber(supersededBy)}` : newStatus;
  rfcText = appendHistoryLine(rfcText, `- ${today}: status ${statusText}`);
  writeFileSync(rfcDocument.absolutePath, rfcText);
  return { relativePath: rfcDocument.relativePath, indexPath: writeRfcIndex(projectRoot, knowledgePath) };
}
