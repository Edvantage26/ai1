// Shared state of the `later` feature: changes that are not decided yet, noted down for later.
// One later entry = one versioned file `.ai1/later/NNNN-<slug>.md` with frontmatter
//   number: <number>, title, size: idea | full, status, created, updated, [decided], [superseded_by]
// and an index `.ai1/later/README.md` whose table is generated between two markers. A later entry is
// not the system: what is in force lives in the knowledge bundle, and an accepted entry must be
// cited there (a concept with the entry in `sources`) before the work counts as carried over.
// The CLI (`ai1 later ...`) and the later hooks both use these functions, so numbering, statuses and
// the index follow one set of rules.

import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { splitFrontmatter, readFrontmatterField, writeFrontmatterField } from '../core/frontmatter.mjs';
import { isFeatureEnabled } from '../core/features.mjs';
import { resolveBundleDirectory, readBundleIndex } from '../okf/okf-bundle.mjs';
import { KNOWLEDGE_BUNDLE_PATH, LATER_DIRECTORY } from '../core/config.mjs';
import { listMarkdownFiles } from '../core/markdown-files.mjs';

export { LATER_DIRECTORY };
export const LATER_INDEX_FILE = 'README.md';
export const LATER_STATUSES = ['draft', 'review', 'accepted', 'rejected', 'superseded', 'implemented'];
export const LATER_SIZES = ['idea', 'full'];
// Still waiting for a decision or for being built.
export const OPEN_LATER_STATUSES = new Set(['draft', 'review', 'accepted']);
// A decision was taken: the entry records when.
const DECIDED_LATER_STATUSES = new Set(['accepted', 'rejected', 'implemented']);
// The decision is in force, so the knowledge bundle must say so.
const CARRIED_LATER_STATUSES = new Set(['accepted', 'implemented']);
const LATER_FILE_PATTERN = /^(\d{4})-([a-z0-9]+(?:-[a-z0-9]+)*)\.md$/;
const SLUG_PATTERN = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;
const DATE_PATTERN = /^\d{4}-\d{2}-\d{2}$/;
const INDEX_START_MARKER = '<!-- later-index:start (generated by `ai1 later index`; do not edit by hand) -->';
const INDEX_END_MARKER = '<!-- later-index:end -->';
const TEMPLATE_DIRECTORY = fileURLToPath(new URL('../../skills/later-write/templates/', import.meta.url));

export function padEntryNumber(entryNumber) {
  return String(entryNumber).padStart(4, '0');
}

export function todayDate(now = new Date()) {
  return now.toISOString().slice(0, 10);
}

export function laterEntryFilePrefix(entryNumber) {
  return `${LATER_DIRECTORY}/${padEntryNumber(entryNumber)}-`;
}

// Every later entry file in .ai1/later, by number: { number, fileNumber, slug, fileName, relativePath, absolutePath,
// title, size, status, created, updated, decided, supersededBy, hasFrontmatter, bodyText }.
export function listLaterEntries(projectRoot) {
  const laterDirectory = join(projectRoot, LATER_DIRECTORY);
  if (!existsSync(laterDirectory)) return [];
  const laterEntries = [];
  for (const fileName of readdirSync(laterDirectory)) {
    const fileMatch = LATER_FILE_PATTERN.exec(fileName);
    if (!fileMatch) continue;
    const absolutePath = join(laterDirectory, fileName);
    const { frontmatterText, bodyText } = splitFrontmatter(readFileSync(absolutePath, 'utf8'));
    const readField = (fieldName) => readFrontmatterField(frontmatterText, fieldName);
    laterEntries.push({
      number: Number(readField('number')) || null,
      fileNumber: Number(fileMatch[1]),
      slug: fileMatch[2],
      fileName,
      relativePath: `${LATER_DIRECTORY}/${fileName}`,
      absolutePath,
      title: readField('title'),
      size: readField('size'),
      status: readField('status'),
      created: readField('created'),
      updated: readField('updated'),
      decided: readField('decided'),
      supersededBy: Number(readField('superseded_by')) || null,
      hasFrontmatter: frontmatterText !== null,
      bodyText,
    });
  }
  return laterEntries.sort((firstEntry, secondEntry) => firstEntry.fileNumber - secondEntry.fileNumber);
}

export function findLaterEntry(laterEntries, entryNumber) {
  return laterEntries.find((laterEntry) => laterEntry.fileNumber === Number(entryNumber));
}

export function describeLaterEntryStatus(laterEntry) {
  return laterEntry.status === 'superseded' && laterEntry.supersededBy
    ? `superseded by ${padEntryNumber(laterEntry.supersededBy)}`
    : laterEntry.status;
}

function buildIndexTable(laterEntries) {
  return [
    INDEX_START_MARKER,
    '| No. | Title | Size | Status | Created | Updated |',
    '|---|---|---|---|---|---|',
    ...laterEntries.map((laterEntry) => `| [${padEntryNumber(laterEntry.fileNumber)}](${laterEntry.fileName}) | ${laterEntry.title || laterEntry.slug} | ${laterEntry.size} | ${describeLaterEntryStatus(laterEntry)} | ${laterEntry.created} | ${laterEntry.updated} |`),
    INDEX_END_MARKER,
  ].join('\n');
}

function buildNewIndexText(indexTable, knowledgePath) {
  const knowledgeText = knowledgePath ? `the knowledge bundle (\`${knowledgePath}/\`)` : 'the project documentation';
  return [
    '# Later',
    '',
    `Large changes and future features, not decided yet, noted down for later. A later entry is not the system: what is in force lives in ${knowledgeText}.`,
    'Create and change entries with `ai1 later new` and `ai1 later set`; this table is regenerated by them.',
    '',
    indexTable,
    '',
  ].join('\n');
}

// The index text that matches the later entry files: the existing README with its table replaced, or a new one.
export function renderLaterIndex(projectRoot, knowledgePath, laterEntries = listLaterEntries(projectRoot)) {
  const indexPath = join(projectRoot, LATER_DIRECTORY, LATER_INDEX_FILE);
  const indexTable = buildIndexTable(laterEntries);
  if (!existsSync(indexPath)) return buildNewIndexText(indexTable, knowledgePath);
  const currentIndexText = readFileSync(indexPath, 'utf8');
  const startIndex = currentIndexText.indexOf(INDEX_START_MARKER);
  const endIndex = currentIndexText.indexOf(INDEX_END_MARKER);
  if (startIndex < 0 || endIndex < startIndex) return `${currentIndexText.trimEnd()}\n\n${indexTable}\n`;
  return currentIndexText.slice(0, startIndex) + indexTable + currentIndexText.slice(endIndex + INDEX_END_MARKER.length);
}

export function writeLaterIndex(projectRoot, knowledgePath) {
  const indexPath = join(projectRoot, LATER_DIRECTORY, LATER_INDEX_FILE);
  mkdirSync(join(projectRoot, LATER_DIRECTORY), { recursive: true });
  writeFileSync(indexPath, renderLaterIndex(projectRoot, knowledgePath));
  return `${LATER_DIRECTORY}/${LATER_INDEX_FILE}`;
}

// Where the index and the brief say decisions live: the bundle path when the okf feature is on.
export function resolveKnowledgePath(config) {
  return isFeatureEnabled('okf', config) ? KNOWLEDGE_BUNDLE_PATH : null;
}

// Bundle to check citations against: only when the okf feature is on and the bundle exists.
export function resolveCitingBundle(projectRoot, config) {
  if (!isFeatureEnabled('okf', config)) return null;
  const bundleDirectory = resolveBundleDirectory(projectRoot);
  return readBundleIndex(bundleDirectory) === null ? null : bundleDirectory;
}

// Problems that make the later folder inconsistent. `bundleDirectory` (when the okf feature is on)
// adds the rule that an accepted or implemented entry is cited by at least one bundle concept.
export function checkLaterEntries(projectRoot, { knowledgePath = null, bundleDirectory = null } = {}) {
  const laterEntries = listLaterEntries(projectRoot);
  const laterProblems = [];
  const seenNumbers = new Map();
  const bundleTexts = bundleDirectory ? listMarkdownFiles(bundleDirectory).map((bundleFile) => readFileSync(bundleFile, 'utf8')) : null;
  for (const laterEntry of laterEntries) {
    const entryLabel = laterEntry.relativePath;
    if (seenNumbers.has(laterEntry.fileNumber)) laterProblems.push(`${entryLabel}: number ${padEntryNumber(laterEntry.fileNumber)} is also used by ${seenNumbers.get(laterEntry.fileNumber)}`);
    seenNumbers.set(laterEntry.fileNumber, entryLabel);
    if (!laterEntry.hasFrontmatter) {
      laterProblems.push(`${entryLabel}: no frontmatter (number, title, size, status, created, updated)`);
      continue;
    }
    if (laterEntry.number !== laterEntry.fileNumber) laterProblems.push(`${entryLabel}: \`number: ${laterEntry.number ?? ''}\` does not match the file number ${laterEntry.fileNumber}`);
    if (!laterEntry.title) laterProblems.push(`${entryLabel}: missing \`title\``);
    if (!LATER_SIZES.includes(laterEntry.size)) laterProblems.push(`${entryLabel}: \`size\` must be one of ${LATER_SIZES.join(', ')}`);
    if (!LATER_STATUSES.includes(laterEntry.status)) laterProblems.push(`${entryLabel}: \`status\` must be one of ${LATER_STATUSES.join(', ')}`);
    for (const dateField of ['created', 'updated']) {
      if (!DATE_PATTERN.test(laterEntry[dateField])) laterProblems.push(`${entryLabel}: \`${dateField}\` must be a date (YYYY-MM-DD)`);
    }
    if (DECIDED_LATER_STATUSES.has(laterEntry.status) && !DATE_PATTERN.test(laterEntry.decided)) {
      laterProblems.push(`${entryLabel}: status ${laterEntry.status} needs \`decided: YYYY-MM-DD\` and its Outcome section filled in`);
    }
    if (laterEntry.status === 'superseded' && !findLaterEntry(laterEntries, laterEntry.supersededBy)) {
      laterProblems.push(`${entryLabel}: status superseded needs \`superseded_by: <number>\` naming an existing entry`);
    }
    if (bundleTexts && CARRIED_LATER_STATUSES.has(laterEntry.status)
      && !bundleTexts.some((bundleText) => bundleText.includes(laterEntryFilePrefix(laterEntry.fileNumber)))) {
      laterProblems.push(`${entryLabel}: ${laterEntry.status} but no concept in ${knowledgePath}/ cites it; record its decisions as concepts (type Decision, \`sources: - resource: ${entryLabel}\`) with /ai1:okf-maintain-knowledge`);
    }
  }
  const indexPath = join(projectRoot, LATER_DIRECTORY, LATER_INDEX_FILE);
  if (laterEntries.length && (!existsSync(indexPath) || readFileSync(indexPath, 'utf8') !== renderLaterIndex(projectRoot, knowledgePath, laterEntries))) {
    laterProblems.push(`${LATER_DIRECTORY}/${LATER_INDEX_FILE} is out of date: run \`ai1 later index\``);
  }
  return laterProblems;
}

// A title with YAML-significant characters (`: `, `#`, a leading quote or bracket) goes in double quotes.
function frontmatterTitle(titleText) {
  const singleLineTitle = titleText.replace(/\n/g, ' ').trim();
  return /: |\s#|^["'\[{&*!|>%@`]/.test(singleLineTitle) ? JSON.stringify(singleLineTitle) : singleLineTitle;
}

function titleFromSlug(slug) {
  const spacedSlug = slug.replace(/-/g, ' ');
  return spacedSlug.charAt(0).toUpperCase() + spacedSlug.slice(1);
}

// Creates .ai1/later/NNNN-<slug>.md from the idea or full template with the next free number, and
// regenerates the index. Returns { entryNumber, relativePath, indexPath }.
export function createLaterEntry(projectRoot, { slug, title, size = 'full', knowledgePath = null, today = todayDate() }) {
  if (!SLUG_PATTERN.test(slug || '')) throw new Error(`the slug must be lowercase words joined by dashes, e.g. prod-guard (got "${slug ?? ''}")`);
  if (!LATER_SIZES.includes(size)) throw new Error(`size must be one of ${LATER_SIZES.join(', ')}`);
  const laterEntries = listLaterEntries(projectRoot);
  const sameSlugEntry = laterEntries.find((laterEntry) => laterEntry.slug === slug);
  if (sameSlugEntry) throw new Error(`${sameSlugEntry.relativePath} already uses the slug "${slug}"`);
  const entryNumber = Math.max(0, ...laterEntries.map((laterEntry) => laterEntry.fileNumber)) + 1;
  const entryText = readFileSync(join(TEMPLATE_DIRECTORY, `${size}.md`), 'utf8')
    .replaceAll('{{number}}', String(entryNumber))
    .replaceAll('{{padded_number}}', padEntryNumber(entryNumber))
    // Replacer functions, so `$&` or `$$` in a title are written as they are.
    .replace('title: {{title}}', () => `title: ${frontmatterTitle(title || titleFromSlug(slug))}`)
    .replaceAll('{{title}}', () => (title || titleFromSlug(slug)).replace(/\n/g, ' ').trim())
    .replaceAll('{{date}}', today);
  mkdirSync(join(projectRoot, LATER_DIRECTORY), { recursive: true });
  const relativePath = `${LATER_DIRECTORY}/${padEntryNumber(entryNumber)}-${slug}.md`;
  writeFileSync(join(projectRoot, relativePath), entryText);
  return { entryNumber, relativePath, indexPath: writeLaterIndex(projectRoot, knowledgePath) };
}

// Adds a line at the end of the History section (created when missing), keeping the spacing around it.
function appendHistoryLine(entryText, historyLine) {
  const historyMatch = /^## History[^\n]*\n/m.exec(entryText);
  if (!historyMatch) return `${entryText.trimEnd()}\n\n## History\n\n${historyLine}\n`;
  const sectionStart = historyMatch.index + historyMatch[0].length;
  const nextHeadingOffset = entryText.slice(sectionStart).search(/^## /m);
  const sectionEnd = nextHeadingOffset < 0 ? entryText.length : sectionStart + nextHeadingOffset;
  const sectionBody = entryText.slice(sectionStart, sectionEnd);
  const trimmedBody = sectionBody.trimEnd();
  const trailingSpace = sectionBody.slice(trimmedBody.length) || '\n';
  return `${entryText.slice(0, sectionStart)}${trimmedBody}\n${historyLine}${trailingSpace}${entryText.slice(sectionEnd)}`;
}

// Moves a later entry to a new status: frontmatter (`status`, `updated`, `decided` when a decision is taken,
// `superseded_by`), a line in its History section, and the index. Returns { relativePath, indexPath }.
export function setLaterEntryStatus(projectRoot, entryNumber, newStatus, { supersededBy = null, knowledgePath = null, today = todayDate() } = {}) {
  if (!LATER_STATUSES.includes(newStatus)) throw new Error(`status must be one of ${LATER_STATUSES.join(', ')}`);
  const laterEntries = listLaterEntries(projectRoot);
  const laterEntry = findLaterEntry(laterEntries, entryNumber);
  if (!laterEntry) throw new Error(`no later entry number ${entryNumber} in ${LATER_DIRECTORY}/`);
  if (newStatus === 'superseded' && !findLaterEntry(laterEntries, supersededBy)) throw new Error('superseded needs --by <number> naming an existing entry');
  let entryText = readFileSync(laterEntry.absolutePath, 'utf8');
  entryText = writeFrontmatterField(entryText, 'status', newStatus);
  entryText = writeFrontmatterField(entryText, 'updated', today);
  if (DECIDED_LATER_STATUSES.has(newStatus) && (newStatus !== 'implemented' || !laterEntry.decided)) {
    entryText = writeFrontmatterField(entryText, 'decided', today);
  }
  if (newStatus === 'superseded') entryText = writeFrontmatterField(entryText, 'superseded_by', Number(supersededBy));
  const statusText = newStatus === 'superseded' ? `superseded by later ${padEntryNumber(supersededBy)}` : newStatus;
  entryText = appendHistoryLine(entryText, `- ${today}: status ${statusText}`);
  writeFileSync(laterEntry.absolutePath, entryText);
  return { relativePath: laterEntry.relativePath, indexPath: writeLaterIndex(projectRoot, knowledgePath) };
}
