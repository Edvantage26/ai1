#!/usr/bin/env node
// Development script: writes the "Skills" and "Hooks" tables of the README from the code, each between
// its two markers. Skills: every `skills/<folder>/SKILL.md` (what it does: the first sentence of its
// description). Hooks: every module of src/core/module-index.mjs (id, feature, event). Descriptions of
// hooks and the origin of both come from src/core/readme-index.mjs.
// test/readme-tables.test.mjs fails when the README is out of date, so after adding a skill or a hook, or
// changing a description or an origin, run:
//
//   npm run readme-tables            # rewrites the tables in README.md
//   npm run readme-tables -- --check # exit 1 when README.md is out of date

import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { splitFrontmatter } from '../src/core/frontmatter.mjs';
import { MODULE_INDEX } from '../src/core/module-index.mjs';
import { HOOK_README_INDEX, SKILL_ORIGIN_INDEX } from '../src/core/readme-index.mjs';
import { featureOfSkill } from '../src/core/skill-customization-index.mjs';
import { loadOkfYaml } from '../src/okf/okf-yaml.mjs';

export function tableMarkers(tableName) {
  return {
    startMarker: `<!-- ${tableName}:start (generated by npm run readme-tables, do not edit) -->`,
    endMarker: `<!-- ${tableName}:end -->`,
  };
}

export function listSkillFolders(repositoryRoot) {
  return readdirSync(join(repositoryRoot, 'skills'), { withFileTypes: true })
    .filter((directoryEntry) => directoryEntry.isDirectory())
    .map((directoryEntry) => directoryEntry.name)
    .sort();
}

// "Later — Note down ... (called by number). Use when ..." -> "Note down ... (called by number)."
export function summarizeSkillDescription(skillDescription) {
  const descriptionWithoutFeature = skillDescription.replace(/\s+/g, ' ').replace(/^[^—]*—\s*/, '');
  const firstSentenceMatch = /^(.*?[.)])(?=\s+[A-Z])/.exec(descriptionWithoutFeature);
  return (firstSentenceMatch ? firstSentenceMatch[1] : descriptionWithoutFeature).trim();
}

function renderSourceLink(originSource) {
  const sourceDetails = [originSource.license, originSource.what].filter(Boolean).join('; ');
  return `[${originSource.name}](${originSource.url})${sourceDetails ? ` (${sourceDetails})` : ''}`;
}

export function renderOrigin(origin) {
  const originParts = [];
  if (origin.importedFrom.length) originParts.push(`Imported from ${origin.importedFrom.map(renderSourceLink).join(', ')}`);
  if (origin.basedOn.length) originParts.push(`${originParts.length ? 'based on' : 'Based on'} ${origin.basedOn.map(renderSourceLink).join(', ')}`);
  return originParts.length ? originParts.join('; ') : 'Written in ai1';
}

function renderTableRow(cellTexts) {
  return `| ${cellTexts.map((cellText) => cellText.replace(/\|/g, '\\|')).join(' | ')} |`;
}

export function renderSkillsTable(repositoryRoot) {
  const tableRows = listSkillFolders(repositoryRoot).map((skillFolder) => {
    const skillOrigin = SKILL_ORIGIN_INDEX[skillFolder];
    if (!skillOrigin) throw new Error(`skills/${skillFolder} has no entry in src/core/readme-index.mjs`);
    const { frontmatterText } = splitFrontmatter(readFileSync(join(repositoryRoot, 'skills', skillFolder, 'SKILL.md'), 'utf8'));
    const skillSummary = summarizeSkillDescription(String(loadOkfYaml(frontmatterText).description || ''));
    return renderTableRow([`\`/ai1:${skillFolder}\``, `\`${featureOfSkill(skillFolder)}\``, skillSummary, renderOrigin(skillOrigin)]);
  });
  return ['| Skill | Feature | What it does | Origin |', '|---|---|---|---|', ...tableRows].join('\n');
}

export function renderHooksTable() {
  const tableRows = MODULE_INDEX.map((moduleEntry) => {
    const hookEntry = HOOK_README_INDEX[moduleEntry.id];
    if (!hookEntry) throw new Error(`module ${moduleEntry.id} has no entry in src/core/readme-index.mjs`);
    return renderTableRow([`\`${moduleEntry.id}\``, `\`${moduleEntry.feature}\``, moduleEntry.event, hookEntry.description, renderOrigin(hookEntry)]);
  });
  return ['| Hook | Feature | Event | What it does | Origin |', '|---|---|---|---|---|', ...tableRows].join('\n');
}

// The README with the text between a table's markers replaced; throws when the markers are missing.
export function replaceReadmeTable(readmeText, tableName, tableText) {
  const { startMarker, endMarker } = tableMarkers(tableName);
  const startIndex = readmeText.indexOf(startMarker);
  const endIndex = readmeText.indexOf(endMarker);
  if (startIndex === -1 || endIndex < startIndex) throw new Error(`README.md has no ${tableName} table markers`);
  return `${readmeText.slice(0, startIndex + startMarker.length)}\n${tableText}\n${readmeText.slice(endIndex)}`;
}

export function renderReadmeTables(readmeText, repositoryRoot) {
  return replaceReadmeTable(replaceReadmeTable(readmeText, 'skills', renderSkillsTable(repositoryRoot)), 'hooks', renderHooksTable());
}

function runReadmeTables(commandArguments) {
  const repositoryRoot = fileURLToPath(new URL('..', import.meta.url));
  const readmePath = join(repositoryRoot, 'README.md');
  const readmeText = readFileSync(readmePath, 'utf8');
  const updatedReadmeText = renderReadmeTables(readmeText, repositoryRoot);
  if (commandArguments.includes('--check')) {
    if (updatedReadmeText === readmeText) return 0;
    process.stderr.write('README.md tables are out of date: run npm run readme-tables\n');
    return 1;
  }
  if (updatedReadmeText !== readmeText) writeFileSync(readmePath, updatedReadmeText);
  process.stdout.write(updatedReadmeText === readmeText ? 'README.md tables already up to date\n' : 'README.md tables updated\n');
  return 0;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) process.exitCode = runReadmeTables(process.argv.slice(2));
