#!/usr/bin/env node
// Development script: writes the "Skills" table of the README from the skills themselves - each
// `skills/<folder>/SKILL.md` (what it does: the first sentence of its description) and
// src/core/skill-origin-index.mjs (where it comes from) - between the two markers below.
// test/readme-skills.test.mjs fails when the README is out of date, so after adding a skill or changing
// its description or origin run:
//
//   npm run readme-skills            # rewrites the table in README.md
//   npm run readme-skills -- --check # exit 1 when README.md is out of date

import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { splitFrontmatter } from '../src/core/frontmatter.mjs';
import { loadOkfYaml } from '../src/okf/okf-yaml.mjs';
import { featureOfSkill } from '../src/core/skill-customization-index.mjs';
import { SKILL_ORIGIN_INDEX } from '../src/core/skill-origin-index.mjs';

export const SKILLS_TABLE_START_MARKER = '<!-- skills:start (generated by npm run readme-skills, do not edit) -->';
export const SKILLS_TABLE_END_MARKER = '<!-- skills:end -->';

export function listSkillFolders(repositoryRoot) {
  return readdirSync(join(repositoryRoot, 'skills'), { withFileTypes: true })
    .filter((directoryEntry) => directoryEntry.isDirectory())
    .map((directoryEntry) => directoryEntry.name)
    .sort();
}

// "Later — Note down ... (called by number). Use when ..." -> "Note down ... (called by number)."
export function summarizeSkillDescription(skillDescription) {
  const descriptionWithoutFeature = skillDescription.replace(/\s+/g, ' ').replace(/^[^—]*—\s*/, '');
  const firstSentenceMatch = /^(.*?[.)])(?=\s+[A-Z])/.exec(descriptionWithoutFeature);
  return (firstSentenceMatch ? firstSentenceMatch[1] : descriptionWithoutFeature).trim();
}

function renderSourceLink(skillSource) {
  const sourceDetails = [skillSource.license, skillSource.what].filter(Boolean).join('; ');
  return `[${skillSource.name}](${skillSource.url})${sourceDetails ? ` (${sourceDetails})` : ''}`;
}

export function renderSkillOrigin(skillOrigin) {
  const originParts = [];
  if (skillOrigin.importedFrom.length) originParts.push(`Imported from ${skillOrigin.importedFrom.map(renderSourceLink).join(', ')}`);
  if (skillOrigin.basedOn.length) originParts.push(`${originParts.length ? 'based on' : 'Based on'} ${skillOrigin.basedOn.map(renderSourceLink).join(', ')}`);
  return originParts.length ? originParts.join('; ') : 'Written in ai1';
}

function escapeTableCell(cellText) {
  return cellText.replace(/\|/g, '\\|');
}

export function renderSkillsTable(repositoryRoot) {
  const tableRows = listSkillFolders(repositoryRoot).map((skillFolder) => {
    const skillOrigin = SKILL_ORIGIN_INDEX[skillFolder];
    if (!skillOrigin) throw new Error(`skills/${skillFolder} has no entry in src/core/skill-origin-index.mjs`);
    const { frontmatterText } = splitFrontmatter(readFileSync(join(repositoryRoot, 'skills', skillFolder, 'SKILL.md'), 'utf8'));
    const skillSummary = summarizeSkillDescription(String(loadOkfYaml(frontmatterText).description || ''));
    return `| \`/ai1:${skillFolder}\` | \`${featureOfSkill(skillFolder)}\` | ${escapeTableCell(skillSummary)} | ${escapeTableCell(renderSkillOrigin(skillOrigin))} |`;
  });
  return ['| Skill | Feature | What it does | Origin |', '|---|---|---|---|', ...tableRows].join('\n');
}

// The README with the table between the markers replaced; throws when the markers are missing.
export function replaceSkillsTable(readmeText, skillsTable) {
  const startIndex = readmeText.indexOf(SKILLS_TABLE_START_MARKER);
  const endIndex = readmeText.indexOf(SKILLS_TABLE_END_MARKER);
  if (startIndex === -1 || endIndex < startIndex) throw new Error('README.md has no skills table markers');
  return `${readmeText.slice(0, startIndex + SKILLS_TABLE_START_MARKER.length)}\n${skillsTable}\n${readmeText.slice(endIndex)}`;
}

function runReadmeSkills(commandArguments) {
  const repositoryRoot = fileURLToPath(new URL('..', import.meta.url));
  const readmePath = join(repositoryRoot, 'README.md');
  const readmeText = readFileSync(readmePath, 'utf8');
  const updatedReadmeText = replaceSkillsTable(readmeText, renderSkillsTable(repositoryRoot));
  if (commandArguments.includes('--check')) {
    if (updatedReadmeText === readmeText) return 0;
    process.stderr.write('README.md skills table is out of date: run npm run readme-skills\n');
    return 1;
  }
  if (updatedReadmeText !== readmeText) writeFileSync(readmePath, updatedReadmeText);
  process.stdout.write(updatedReadmeText === readmeText ? 'README.md skills table already up to date\n' : 'README.md skills table updated\n');
  return 0;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) process.exitCode = runReadmeSkills(process.argv.slice(2));
